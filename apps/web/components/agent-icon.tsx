function initialsFor(agentId: string): string {
  return agentShortName(agentId)
    .split(/\s+/)
    .map((part) => part[0])
    .join("")
    .slice(0, 2)
    .toUpperCase();
}

export function AgentIcon({ agentId, size = "sm", className }: AgentIconProps) {
  const icon = BRAND_ICONS[agentId];
  const name = agentDisplayName(agentId);

  if (!icon) {
    return (
      <span
        aria-hidden="true"
        className={cn(
          "inline-flex shrink-0 items-center justify-center rounded border border-plexus-border bg-plexus-surface-2 font-mono font-semibold text-plexus-text-2",
          CONTAINER_SIZE[size],
          INITIAL_SIZE[size],
          className,
        )}
        title={name}
      >
        {initialsFor(agentId)}
      </span>
    );
  }

  return (
    <span
      aria-hidden="true"
      className={cn(
        "inline-flex shrink-0 items-center justify-center rounded border",
        CONTAINER_SIZE[size],
        icon.className,
        className,
      )}
      title={name}
    >
      <svg
        role="img"
        viewBox="0 0 24 24"
        className={cn(SVG_SIZE[size], icon.iconClassName)}
        fill="currentColor"
      >
        <title>{icon.title}</title>
        <path d={icon.path} />
      </svg>
    </span>
  );
}

export function AgentName({
  agentId,
  label,
  iconSize = "sm",
  className,
  labelClassName,
}: AgentNameProps) {
  return (
    <span className={cn("inline-flex min-w-0 items-center gap-1.5", className)}>
      <AgentIcon agentId={agentId} size={iconSize} />
      <span className={cn("truncate", labelClassName)}>{label ?? agentDisplayName(agentId)}</span>
    </span>
  );
}
